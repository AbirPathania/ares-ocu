"""Gaussian splat scenes: a place reconstructed from photographs, drawn from any camera.

A splat scene is some hundreds of thousands of soft, coloured ellipsoids (3D Gaussians) that training fitted to the video
frames of a real place, so that drawing them from the position of one of those frames gives back that frame. Drawn from a
position near it, they give what a camera there would have seen. Nothing in it is modelled or generated by this
program; it is the footage's ground, grass, stones and trees, as seen.

How one is drawn: every splat is projected to the screen as an ellipse (its 3D covariance carried through the
camera's projection, after the EWA splatting of Zwicker et al., as 3D Gaussian Splatting does), its colour is the one
the splat has from this direction (spherical harmonics up to degree two, which is how a shiny stone or a leaf
shows a different colour from each side), and the ellipses are blended back to front. The sort is on the CPU and is the
cost; everything else is on the GPU, with each splat's data in a float texture and an index buffer, which is all that is
rewritten when the camera moves.

Coordinates are COLMAP's (the camera looks along +z, x is right and y is down) and the scene's own scale and
orientation, whatever the reconstruction came out as. Placing it in the simulation's world is `SplatPlacement`.

No Qt import belongs in this file.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

SH_C0 = 0.28209479177387814
TEXELS = 10  # per splat in the data texture


@dataclass
class SplatCloud:
    """The splats as arrays, ready to upload. Opacity is already through its sigmoid, scale through its exponential."""

    position: np.ndarray  # (n, 3) float32
    covariance: np.ndarray  # (n, 6) float32: xx, xy, xz, yy, yz, zz of R S S^T R^T
    opacity: np.ndarray  # (n,) float32, 0..1
    dc: np.ndarray  # (n, 3) float32: the degree-0 colour coefficients
    rest: np.ndarray  # (n, 3, 8) float32: degrees 1 and 2, per colour channel (zero if the file has less)

    def __len__(self) -> int:
        return len(self.position)

    def subset(self, keep: np.ndarray) -> "SplatCloud":
        return SplatCloud(self.position[keep], self.covariance[keep], self.opacity[keep], self.dc[keep], self.rest[keep])


def load_ply(path: str | Path, min_opacity: float = 0.02) -> SplatCloud:
    """Read a splat PLY (binary, little endian, the layout 3D Gaussian Splatting trainers write).

    The file is data from a tool this program does not control, so the header is checked, the size is checked against
    the header, and only the named properties are read."""
    path = Path(path)
    with open(path, "rb") as handle:
        first = handle.readline().strip()
        if first != b"ply":
            raise ValueError("not a PLY file")
        count, props, fmt = 0, [], ""
        while True:
            line = handle.readline().decode("ascii", "replace").strip()
            if not line:
                raise ValueError("PLY header ended early")
            if line.startswith("format"):
                fmt = line.split()[1]
            elif line.startswith("element vertex"):
                count = int(line.split()[2])
            elif line.startswith("property"):
                _, kind, name = line.split()[:3]
                props.append((name, kind))
            elif line == "end_header":
                break
        if fmt != "binary_little_endian" or any(kind != "float" for _, kind in props):
            raise ValueError("only binary little-endian float PLY is read")
        offset = handle.tell()
    if count <= 0 or count > 20_000_000:
        raise ValueError("implausible splat count")
    dtype = np.dtype([(name, "<f4") for name, _ in props])
    if path.stat().st_size != offset + count * dtype.itemsize:
        raise ValueError("PLY size does not match its header")
    data = np.fromfile(path, dtype=dtype, count=count, offset=offset)

    names = set(data.dtype.names)
    position = np.stack([data["x"], data["y"], data["z"]], axis=1)
    opacity = 1.0 / (1.0 + np.exp(-data["opacity"]))
    scale = np.exp(np.stack([data["scale_0"], data["scale_1"], data["scale_2"]], axis=1))
    q = np.stack([data["rot_0"], data["rot_1"], data["rot_2"], data["rot_3"]], axis=1)  # w, x, y, z
    q /= np.maximum(np.linalg.norm(q, axis=1, keepdims=True), 1e-9)
    w, x, y, z = q.T
    rot = np.stack([
        1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y),
        2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x),
        2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)], axis=1).reshape(-1, 3, 3)
    m = rot * scale[:, None, :]  # R S
    sigma = m @ m.transpose(0, 2, 1)
    covariance = np.stack([sigma[:, 0, 0], sigma[:, 0, 1], sigma[:, 0, 2], sigma[:, 1, 1], sigma[:, 1, 2], sigma[:, 2, 2]], axis=1)
    dc = np.stack([data["f_dc_0"], data["f_dc_1"], data["f_dc_2"]], axis=1)
    rest = np.zeros((count, 3, 8), dtype=np.float32)
    per_channel = sum(1 for n in names if n.startswith("f_rest_")) // 3
    for c in range(3):
        for k in range(min(per_channel, 8)):
            rest[:, c, k] = data[f"f_rest_{c * per_channel + k}"]
    cloud = SplatCloud(position.astype(np.float32), covariance.astype(np.float32), opacity.astype(np.float32), dc.astype(np.float32), rest)
    keep = (opacity >= min_opacity) & np.isfinite(position).all(axis=1) & np.isfinite(covariance).all(axis=1)
    return cloud.subset(keep) if not keep.all() else cloud


# --- cameras ----------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Intrinsics:
    width: int
    height: int
    fx: float
    fy: float
    cx: float
    cy: float

    def scaled(self, width: int) -> "Intrinsics":
        s = width / self.width
        return Intrinsics(width, int(round(self.height * s)), self.fx * s, self.fy * s, self.cx * s, self.cy * s)


@dataclass(frozen=True)
class Pose:
    """World-to-camera, in COLMAP's convention: x_cam = rotation @ x_world + translation."""

    rotation: np.ndarray  # (3, 3)
    translation: np.ndarray  # (3,)
    name: str = ""

    @property
    def centre(self) -> np.ndarray:
        return -self.rotation.T @ self.translation


def read_colmap_text(folder: str | Path) -> tuple[Intrinsics, list[Pose]]:
    """Cameras and image poses from a COLMAP text model (cameras.txt and images.txt), sorted by image name."""
    folder = Path(folder)
    camera_line = next(l for l in (folder / "cameras.txt").read_text().splitlines() if l and not l.startswith("#"))
    parts = camera_line.split()
    model, width, height = parts[1], int(parts[2]), int(parts[3])
    p = [float(v) for v in parts[4:]]
    if model in ("SIMPLE_PINHOLE", "SIMPLE_RADIAL", "RADIAL"):
        k = Intrinsics(width, height, p[0], p[0], p[1], p[2])
    elif model in ("PINHOLE", "OPENCV"):
        k = Intrinsics(width, height, p[0], p[1], p[2], p[3])
    else:
        raise ValueError(f"camera model {model} is not read")
    poses: list[Pose] = []
    lines = [l for l in (folder / "images.txt").read_text().splitlines() if not l.startswith("#")]
    for header in lines[0::2]:
        if not header.strip():
            continue
        v = header.split()
        qw, qx, qy, qz = map(float, v[1:5])
        t = np.array(list(map(float, v[5:8])))
        rot = np.array([
            [1 - 2 * (qy * qy + qz * qz), 2 * (qx * qy - qw * qz), 2 * (qx * qz + qw * qy)],
            [2 * (qx * qy + qw * qz), 1 - 2 * (qx * qx + qz * qz), 2 * (qy * qz - qw * qx)],
            [2 * (qx * qz - qw * qy), 2 * (qy * qz + qw * qx), 1 - 2 * (qx * qx + qy * qy)]])
        poses.append(Pose(rot, t, v[9]))
    poses.sort(key=lambda p: p.name)
    return k, poses


# --- drawing ----------------------------------------------------------------------------------------------------------

VERTEX = """
#version 330
uniform sampler2D u_data;     // 10 texels per splat, see SplatRenderer.__init__
uniform mat3 u_rot;           // world to camera
uniform vec3 u_trans;
uniform vec3 u_eye;           // camera position in the world
uniform vec4 u_k;             // fx, fy, cx, cy in pixels
uniform vec2 u_size;          // width, height in pixels
uniform float u_gain;
in vec2 in_corner;
in uint in_index;
out vec2 v_corner;
out vec4 v_colour;

vec4 texel(int splat, int k) {
    int i = splat * 10 + k;
    return texelFetch(u_data, ivec2(i & 2047, i >> 11), 0);
}

void main() {
    int s = int(in_index);
    vec4 t0 = texel(s, 0), t1 = texel(s, 1), t2 = texel(s, 2), t3 = texel(s, 3), t4 = texel(s, 4);
    vec4 t5 = texel(s, 5), t6 = texel(s, 6), t7 = texel(s, 7), t8 = texel(s, 8), t9 = texel(s, 9);
    vec3 pos = t0.xyz;
    vec3 c = u_rot * pos + u_trans;
    if (c.z < 0.15) { gl_Position = vec4(2.0, 2.0, 2.0, 1.0); return; }
    // the covariance in camera space, then through the projection's local linearisation
    mat3 sigma = mat3(t1.x, t1.y, t1.z,  t1.y, t1.w, t2.x,  t1.z, t2.x, t2.y);   // symmetric: xx xy xz / xy yy yz / xz yz zz
    mat3 cam = u_rot * sigma * transpose(u_rot);
    float iz = 1.0 / c.z;
    vec3 j0 = vec3(u_k.x * iz, 0.0, -u_k.x * c.x * iz * iz);
    vec3 j1 = vec3(0.0, u_k.y * iz, -u_k.y * c.y * iz * iz);
    float a = dot(j0, cam * j0) + 0.3;
    float b = dot(j0, cam * j1);
    float d = dot(j1, cam * j1) + 0.3;
    float mid = 0.5 * (a + d);
    float rad = length(vec2(0.5 * (a - d), b));
    float l1 = mid + rad, l2 = max(mid - rad, 0.05);
    vec2 axis = normalize(abs(b) < 1e-6 ? vec2(a >= d ? 1.0 : 0.0, a >= d ? 0.0 : 1.0) : vec2(b, l1 - a));
    vec2 major = axis * min(3.0 * sqrt(l1), 900.0);
    vec2 minor = vec2(-axis.y, axis.x) * min(3.0 * sqrt(l2), 900.0);
    vec2 px = vec2(u_k.x * c.x * iz + u_k.z, u_k.y * c.y * iz + u_k.w);
    vec2 pos_px = px + in_corner.x * major + in_corner.y * minor;
    vec2 ndc = vec2(2.0 * pos_px.x / u_size.x - 1.0, 1.0 - 2.0 * pos_px.y / u_size.y);
    gl_Position = vec4(ndc, 0.0, 1.0);
    v_corner = in_corner * 3.0;

    // colour from this direction: spherical harmonics, degree 0 to 2
    vec3 d_w = normalize(pos - u_eye);
    float x = d_w.x, y = d_w.y, z = d_w.z;
    float xx = x * x, yy = y * y, zz = z * z, xy = x * y, yz = y * z, xz = x * z;
    float b1 = -0.4886025119 * y, b2 = 0.4886025119 * z, b3 = -0.4886025119 * x;
    float b4 = 1.0925484306 * xy, b5 = -1.0925484306 * yz, b6 = 0.3153915653 * (2.0 * zz - xx - yy);
    float b7 = -1.0925484306 * xz, b8 = 0.5462742153 * (xx - yy);
    vec3 col = vec3(t2.z, t2.w, t3.x) * 0.28209479 + 0.5;
    col.r += b1 * t3.y + b2 * t3.z + b3 * t3.w + b4 * t4.x + b5 * t4.y + b6 * t4.z + b7 * t4.w + b8 * t5.x;
    col.g += b1 * t5.y + b2 * t5.z + b3 * t5.w + b4 * t6.x + b5 * t6.y + b6 * t6.z + b7 * t6.w + b8 * t7.x;
    col.b += b1 * t7.y + b2 * t7.z + b3 * t7.w + b4 * t8.x + b5 * t8.y + b6 * t8.z + b7 * t8.w + b8 * t9.x;
    v_colour = vec4(max(col, 0.0) * u_gain, t0.w);
}
"""

FRAGMENT = """
#version 330
in vec2 v_corner;
in vec4 v_colour;
out vec4 f_color;
void main() {
    float r2 = dot(v_corner, v_corner);
    if (r2 > 9.0) discard;
    float alpha = v_colour.a * exp(-0.5 * r2);
    if (alpha < 1.0 / 255.0) discard;
    f_color = vec4(v_colour.rgb, min(alpha, 0.99));
}
"""


class SplatRenderer:
    """Draws one SplatCloud into the framebuffer that is current on `ctx`."""

    def __init__(self, ctx, cloud: SplatCloud) -> None:
        import moderngl  # noqa: F401  (the context already comes from it)

        self.ctx = ctx
        self.cloud = cloud
        self.program = ctx.program(vertex_shader=VERTEX, fragment_shader=FRAGMENT)
        n = len(cloud)
        # 40 floats a splat, ten texels: position and opacity, the six covariance terms, the degree-0 colour, then the
        # twenty-four higher-order coefficients (eight for red, eight for green, eight for blue), then padding.
        v = np.zeros((n, TEXELS * 4), dtype=np.float32)
        v[:, 0:3], v[:, 3] = cloud.position, cloud.opacity
        v[:, 4:10] = cloud.covariance
        v[:, 10:13] = cloud.dc
        v[:, 13:37] = cloud.rest.reshape(n, 24)
        total = n * TEXELS
        width = 2048
        height = (total + width - 1) // width
        data = np.zeros((height * width, 4), dtype=np.float32)
        data[:total] = v.reshape(-1, 4)
        self.texture = ctx.texture((width, height), 4, data.tobytes(), dtype="f4")
        self.texture.filter = (ctx.NEAREST, ctx.NEAREST)
        corners = np.array([[-1, -1], [1, -1], [1, 1], [-1, 1]], dtype=np.float32)
        self.corner_buffer = ctx.buffer(corners.tobytes())
        self.index_buffer = ctx.buffer(reserve=max(n * 4, 16))
        self.quad = ctx.buffer(np.array([0, 1, 2, 0, 2, 3], dtype=np.uint32).tobytes())
        self.vao = ctx.vertex_array(
            self.program,
            [(self.corner_buffer, "2f", "in_corner"), (self.index_buffer, "1u/i", "in_index")],
            self.quad,
        )
        self._last_count = 0

    def sort_for(self, pose: Pose, near: float = 0.15) -> np.ndarray:
        """Indices of the splats in front of the camera, far to near."""
        depth = self.cloud.position @ pose.rotation[2] + pose.translation[2]
        visible = np.nonzero(depth > near)[0]
        order = visible[np.argsort(-depth[visible], kind="stable")]
        return order.astype(np.uint32)

    def render(self, pose: Pose, k: Intrinsics, gain: float = 1.0) -> None:
        """Draw into the current framebuffer, blending over what is there (clear it first, or draw the sky first)."""
        order = self.sort_for(pose)
        self._last_count = len(order)
        if not len(order):
            return
        self.index_buffer.write(order.tobytes())
        p = self.program
        p["u_data"].value = 7
        self.texture.use(location=7)
        p["u_rot"].write(np.ascontiguousarray(pose.rotation.T, dtype=np.float32).tobytes())  # GLSL is column-major
        p["u_trans"].value = tuple(float(v) for v in pose.translation)
        p["u_eye"].value = tuple(float(v) for v in pose.centre)
        p["u_k"].value = (k.fx, k.fy, k.cx, k.cy)
        p["u_size"].value = (float(k.width), float(k.height))
        p["u_gain"].value = gain
        self.ctx.enable(self.ctx.BLEND)
        self.ctx.blend_func = (self.ctx.SRC_ALPHA, self.ctx.ONE_MINUS_SRC_ALPHA)
        self.ctx.disable(self.ctx.DEPTH_TEST)
        self.ctx.disable(self.ctx.CULL_FACE)
        self.vao.render(instances=len(order))
